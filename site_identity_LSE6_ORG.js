    root.localStorage?.setItem("LSE6.ANCHOR.PRIMARY", SITE.anchors[0]);
    root.localStorage?.setItem("LSE6.ANCHOR.SECONDARY", SITE.anchors[1]);
    root.localStorage?.setItem("LSE6.ANCHOR.EQUAL", "true");
