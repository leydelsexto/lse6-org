    root.localStorage?.setItem("LSE6.NAME.OFFICIAL", SITE.officialName);
    root.localStorage?.setItem(
      "LSE6.NAME.CENTER_OFFICIAL",
      SITE.centerOfficialName,
    );
    root.localStorage?.setItem("LSE6.AXIS", SITE.axis);
    root.localStorage?.setItem("LSE6.PULSE", buildMachinePulse());
    root.localStorage?.setItem("LSE6.ORG.STATE", SITE.state);
    root.localStorage?.setItem("LSE6.ORG.MODE", SITE.mode);
