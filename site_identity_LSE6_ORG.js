function ensureCanonicalIdentityLinks(doc = root.document) {
  if (!doc?.head) return;

  const ensureLink = (selector, attributes) => {
    let link = doc.querySelector(selector);
    if (!link) {
      link = doc.createElement("link");
      doc.head.appendChild(link);
    }

    Object.entries(attributes).forEach(([name, value]) => {
      link.setAttribute(name, value);
    });
  };

  ensureLink('link[rel="canonical"]', {
    rel: "canonical",
    href: SITE.extensionDomain,
  });

  ensureLink('link[data-lse6="center"]', {
    rel: "home",
    href: SITE.centerDomain,
    "data-lse6": "center",
  });

  ensureLink('link[data-lse6="center-alternate"]', {
    rel: "alternate",
    href: SITE.centerDomain,
    hreflang: "es-MX",
    "data-lse6": "center-alternate",
  });
}

